"""data.py - turn the original game's data files into C tables.

Runs at build time, like convert.py (make runs it whenever data/ or this
file changes). It writes build/data.c and build/data.h.

The original kept its data in pipe-separated text files (data/), loaded
into a database by seed.py. The NES has no database or filesystem, so the
same rows become constant C structs in the ROM.

Where they go: all in one switchable bank, DATA_BANK, so they don't use up
the fixed bank, which the code needs. The rule for the C side: switch to
DATA_BANK and copy what you need into RAM before using it. (Anything else
that switches banks, like loading art, would swap the data out from under
a pointer into it.)
"""

from pathlib import Path

DATA = Path("data")
DATA_BANK = 14        # the last switchable bank; convert.py keeps the art out of it


def rows(name):
    """The rows of a data file, each split at the pipes. Lines starting
    with # are column headings."""
    lines = (DATA / name).read_text().splitlines()
    return [[field.strip() for field in line.split("|")]
            for line in lines if line.strip() and not line.startswith("#")]


def c_string(text):
    """A C string literal. The font has the printable ASCII characters
    (32-126) and nothing else, so anything outside that is an error here,
    not a blank square on screen."""
    for ch in text:
        if not " " <= ch <= "~":
            raise SystemExit(f"data: {ch!r} in {text!r} isn't in the font")
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


# The slots a story template can have, and the code each is stored as.
SLOTS = {"name": 1, "regent": 2, "item": 3, "killer": 4}


def strings(source, name, table, texts, literal=False):
    """A table of strings: each its own named array (cc65 would put string
    literals in the fixed bank), then an array of pointers to them. With
    literal=True, the texts are already C string literals."""
    for number, text in enumerate(texts):
        source.append(f"static const char {name}_{number}[] = "
                      f"{text if literal else c_string(text)};\n")
    source.append(f"\nconst char * const {table}[{len(texts)}] = {{\n"
                  + "".join(f"    {name}_{number},\n" for number in range(len(texts)))
                  + "};\n\n")


def main():
    enemies = rows("enemies")
    classes = rows("class")

    # Fighters' names are stored inside their records (not as pointers), so
    # a fight can copy a whole record into RAM in one go. Names are in
    # capitals: the original always showed them that way.
    name_size = max(len(row[0]) for row in enemies + classes) + 1

    def stats(name, str_, dex, arm, weap, hp, hp_max):
        if hp != hp_max:
            raise SystemExit(f"data: {name} starts below full HP")
        return f"{{ {c_string(name.upper())}, {str_}, {dex}, {arm}, {weap}, {hp} }}"

    source = ["/* data.c - generated by tools/data.py from data/. Don't edit. */\n\n",
              '#include "data.h"\n\n',
              f'#pragma rodata-name (push, "BANK{DATA_BANK:02d}")\n\n']

    # data/enemies: name, level, experience, str, dex, arm, weap, hp, hp
    # max, sprite position (the art's order, which convert.py follows), and
    # a description.
    # Each description is a named array, not a "string" in the struct: cc65
    # puts string literals in the fixed bank, whatever bank the struct is in.
    for number, row in enumerate(enemies):
        source.append(f"static const char enemy_desc_{number}[] = {c_string(row[-1])};\n")
    source.append(f"\nconst Enemy enemies[{len(enemies)}] = {{\n")
    for number, (name, level, exp, str_, dex, arm, weap, hp, hp_max, _, _) in enumerate(enemies):
        source.append(f"    {{ {stats(name, str_, dex, arm, weap, hp, hp_max)}, "
                      f"{level}, {exp}, enemy_desc_{number} }},\n")
    source.append("};\n\n")

    # data/class: name, str, dex, arm, weap, hp, hp max, then int, cha,
    # sprite position and bonus, which the original never used in play.
    source.append(f"const Stats classes[{len(classes)}] = {{\n")
    for name, str_, dex, arm, weap, hp, hp_max, *_ in classes:
        source.append(f"    {stats(name, str_, dex, arm, weap, hp, hp_max)},\n")
    source.append("};\n\n")

    # data/items: name, description (the description isn't shown yet).
    items = [row[0].upper() for row in rows("items")]
    if "FUTURE TECH" not in items:
        raise SystemExit("data: no Future Tech in data/items")
    strings(source, "item", "items", items)

    # data/regents: name, title, species, description, attitude. Only the
    # title and name were ever shown, always together ("KING HACHIKO"), so
    # that's what's stored.
    regents = [f"{title} {name}".upper() for name, title, *_ in rows("regents")]
    strings(source, "regent", "regents", regents)

    # data/story_blocks: the story's templates, each a block type and its
    # text. $slot$ is filled in when the story is told (see story.c), and
    # stored as one byte, a code below 32: the font starts at 32 (the space),
    # so a code can't be mistaken for a character.
    blocks = rows("story_blocks")
    lengths = {"name": name_size - 1,
               "regent": max(map(len, regents)),
               "item": max(map(len, items)),
               "killer": name_size - 1}
    story_size = 0
    templates = []
    for _, text in blocks:
        pieces = text.split("$")
        if len(pieces) % 2 == 0:
            raise SystemExit(f"data: a $ without its partner in {text!r}")
        size, parts = 1, []
        for number, piece in enumerate(pieces):
            if number % 2:              # between a pair of $: a slot
                if piece not in SLOTS:
                    raise SystemExit(f"data: unknown slot ${piece}$ in {text!r}")
                size += lengths[piece]
                parts.append(f'"\\{SLOTS[piece]:03o}"')
            elif piece:
                size += len(piece)
                parts.append(c_string(piece))
        story_size = max(story_size, size)
        templates.append(" ".join(parts))
    strings(source, "story", "stories", templates, literal=True)
    source.append("#pragma rodata-name (pop)\n")

    header = [
        "/* data.h - generated by tools/data.py from data/. Don't edit.\n"
        " *\n"
        " * The tables are in bank DATA_BANK: switch to it with mmc1_set_bank()\n"
        " * and copy what's needed into RAM before using it. */\n\n"
        "#ifndef DATA_H\n#define DATA_H\n\n",
        f"#define DATA_BANK {DATA_BANK}\n\n",
        "/* A fighter: name, strength, dexterity (speed and aim), armor, weapon,\n"
        " * hit points. */\n",
        f"#define NAME_SIZE {name_size}\n",
        "typedef struct {\n"
        "    char name[NAME_SIZE];\n"
        "    unsigned char str, dex, arm, weap, hp;\n"
        "} Stats;\n\n",
        "/* An enemy: its stats, its level and the experience it's worth (both\n"
        " * unused until Milestone 6), and a description. */\n"
        "typedef struct {\n"
        "    Stats stats;\n"
        "    unsigned char level, exp;\n"
        "    const char *desc;\n"
        "} Enemy;\n\n",
        "/* The longest description, for sizing buffers. */\n",
        f"#define DESC_LONGEST {max(len(row[-1]) for row in enemies)}\n\n",
        "/* In the battle art's order. The first is the boss. */\n",
        f"#define ENEMIES {len(enemies)}\n",
        "#define BOSS 0\n",
        "extern const Enemy enemies[ENEMIES];\n\n",
        "/* The player's classes. */\n",
        f"#define CLASSES {len(classes)}\n",
    ]
    for number, row in enumerate(classes):
        header.append(f"#define CLASS_{row[0].upper()} {number}\n")
    header.append("extern const Stats classes[CLASSES];\n\n")

    header += [
        "/* Names, in capitals. Future Tech is only for a player who has\n"
        " * collected every other item. */\n",
        f"#define ITEMS {len(items)}\n",
        f"#define ITEM_FUTURE_TECH {items.index('FUTURE TECH')}\n",
        "extern const char * const items[ITEMS];\n\n",
        "/* Title and name, in capitals. */\n",
        f"#define REGENTS {len(regents)}\n",
        "extern const char * const regents[REGENTS];\n\n",
        "/* The story's templates: text, with a SLOT_ code wherever a value\n"
        " * goes. STORY_SIZE fits the longest, filled in, plus its 0. */\n",
    ]
    for slot, code in SLOTS.items():
        header.append(f"#define SLOT_{slot.upper()} {code}\n")
    for number, (block_type, _) in enumerate(blocks):
        header.append(f"#define STORY_{block_type.upper()} {number}\n")
    header += [f"#define STORIES {len(blocks)}\n",
               f"#define STORY_SIZE {story_size}\n",
               "extern const char * const stories[STORIES];\n\n#endif\n"]

    Path("build/data.c").write_text("".join(source))
    Path("build/data.h").write_text("".join(header))
    print(f"wrote build/data.c and build/data.h: {len(enemies)} enemies, "
          f"{len(classes)} classes, {len(items)} items, {len(regents)} regents, "
          f"{len(blocks)} story blocks")


if __name__ == "__main__":
    main()
